#!/usr/bin/env python3

import argparse
import subprocess
import sys
from pathlib import Path

from fontTools import subset

NEW_FAMILY = "wsap Playing Cards"
CARD_RANGE = range(0x1F0A0, 0x1F100)

def find_adwaita():
    out = subprocess.run(
        ["fc-match", "--format=%{file}", "Adwaita Mono:style=Regular"],
        capture_output=True, text=True, check=True).stdout.strip()
    if not out or not Path(out).is_file():
        sys.exit("fc-match could not locate Adwaita Mono Regular")
    return out

def build_subset(path):
    opts = subset.Options()
    opts.name_IDs = ["*"]
    opts.hinting = True
    opts.glyph_names = False
    font = subset.load_font(path, opts)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=[0x20] + list(CARD_RANGE))
    subsetter.subset(font)

    renames = {
        1: NEW_FAMILY,
        3: f"{NEW_FAMILY} Regular (subset of Adwaita Mono)",
        4: f"{NEW_FAMILY} Regular",
        6: "wsapPlayingCards-Regular",
        16: NEW_FAMILY,
        17: "Regular",
    }
    for rec in font["name"].names:
        if rec.nameID in renames:
            rec.string = renames[rec.nameID].encode(
                rec.getEncoding(), errors="replace")
    return font

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("font", type=Path, nargs="?",
                        help="AdwaitaMono-Regular.ttf (default: fc-match)")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    source = args.font or Path(find_adwaita())
    font = build_subset(source)

    tmp = Path("/tmp/wsap-cards-subset.ttf")
    font.save(tmp)
    data = tmp.read_bytes()
    tmp.unlink()

    version = next((r.toUnicode() for r in font["name"].names
                    if r.nameID == 5), "unknown version")
    out = [
        f"/* Generated by tools/generate_cards_font.py from",
        f" * {source} ({version}).",
        f" *",
        f" * Adwaita Mono subset covering U+0020 and U+1F0A0-U+1F0FF",
        f" * (Playing Cards), renamed to \"{NEW_FAMILY}\".  The source font is",
        f" * Copyright 2015-2026, Renzhi Li (aka. Belleve Invis), licensed under",
        f" * the SIL Open Font License 1.1; the full license text is carried in",
        f" * the font's own name table (nameIDs 13/14).",
        f" */",
        "",
        "static const unsigned char embedded_cards_font[] = {",
    ]
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    out.append("};")
    args.output.write_text("\n".join(out) + "\n")
    print(f"{args.output}: {len(data)} bytes, "
          f"{font['maxp'].numGlyphs} glyphs")

if __name__ == "__main__":
    main()
