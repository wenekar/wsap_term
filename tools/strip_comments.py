#!/usr/bin/env python3
import re
import sys

HEADER_RE = re.compile(r"copyright|licen[cs]e|SPDX|generated by|generated from",
                       re.IGNORECASE)

def _keep_c_header(src):
    i, n = 0, len(src)
    end = 0
    matched = False
    while i < n:
        gap = 0
        while i < n and src[i] in " \t\r\n":
            gap += src[i] == "\n"
            i += 1
        if matched and gap > 1:
            break
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j + 1
        elif src.startswith("/*", i):
            j = src.find("*/", i)
            j = n if j < 0 else j + 2
        else:
            break
        if not matched and not HEADER_RE.search(src[i:j]):
            break
        matched = True
        end = j
        i = j
    return end

def _copy_quoted(src, i, out, line_start):
    quote = src[i]
    out.append(quote)
    i += 1
    n = len(src)
    while i < n:
        if src[i] == "\\" and i + 1 < n:
            out.append(src[i])
            out.append(src[i + 1])
            i += 2
            continue
        out.append(src[i])
        if src[i] == quote:
            return i + 1, line_start
        if src[i] == "\n":
            line_start = len(out)
        i += 1
    return i, line_start

def strip_c(src):
    keep = _keep_c_header(src)
    head, src = src[:keep], src[keep:]
    out = []
    i, n = 0, len(src)
    line_start = 0
    line_has_code = False
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""

        if c in "\"'":
            line_has_code = True
            i, line_start = _copy_quoted(src, i, out, line_start)
            continue

        if c == "/" and nxt == "/":
            while i < n and src[i] != "\n":
                i += 1
            if not line_has_code:
                del out[line_start:]
                if i < n:
                    i += 1
            continue

        if c == "/" and nxt == "*":
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            spanned = src.count("\n", i, j)
            if not line_has_code:
                k = j
                while k < n and src[k] in " \t":
                    k += 1
                if k >= n or src[k] == "\n":
                    del out[line_start:]
                    i = k + 1 if k < n else k
                    continue
            out.append(" " if not spanned else "\n" * spanned)
            if spanned:
                line_start = len(out)
                line_has_code = False
            i = j
            continue

        if c == "\n":
            out.append(c)
            line_start = len(out)
            line_has_code = False
            i += 1
            continue

        out.append(c)
        if not c.isspace():
            line_has_code = True
        i += 1

    result = head + "".join(out)
    result = re.sub(r"[ \t]+$", "", result, flags=re.MULTILINE)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result

def strip_py(src):
    out = []
    i, n = 0, len(src)
    line_start = 0
    line_has_code = False
    while i < n:
        c = src[i]

        for q in ('"""', "'''"):
            if src.startswith(q, i):
                j = src.find(q, i + 3)
                j = n if j < 0 else j + 3
                out.append(src[i:j])
                line_start = len(out)
                line_has_code = True
                i = j
                break
        else:
            if c in "\"'":
                line_has_code = True
                i, line_start = _copy_quoted(src, i, out, line_start)
                continue

            if c == "#":
                if i == 0 and src.startswith("#!"):
                    j = src.find("\n", i)
                    j = n if j < 0 else j
                    out.append(src[i:j])
                    line_has_code = True
                    i = j
                    continue
                while i < n and src[i] != "\n":
                    i += 1
                if not line_has_code:
                    del out[line_start:]
                    if i < n:
                        i += 1
                continue

            if c == "\n":
                out.append(c)
                line_start = len(out)
                line_has_code = False
                i += 1
                continue

            out.append(c)
            if not c.isspace():
                line_has_code = True
            i += 1

    result = "".join(out)
    result = re.sub(r"[ \t]+$", "", result, flags=re.MULTILINE)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result

C_SUFFIXES = (".c", ".h", ".cpp", ".inc", ".vert", ".frag", ".comp", ".css")
HASH_SUFFIXES = (".py", ".build", ".options", ".gitignore")
HASH_NAMES = ("Makefile",)
SHELL_SUFFIXES = (".sh", ".bash", ".zsh", ".ksh", ".fish")
SHELL_SHEBANG = re.compile(rb"^#!.*\b(sh|bash|zsh|ksh|dash|fish)\b")

def is_shell(path, raw):
    return path.endswith(SHELL_SUFFIXES) or bool(SHELL_SHEBANG.match(raw))

def main():
    skipped = []
    for path in sys.argv[1:]:
        with open(path, "rb") as f:
            raw = f.read()
        if is_shell(path, raw):
            skipped.append((path, "shell"))
            continue
        src = raw.decode("utf-8")
        name = path.rsplit("/", 1)[-1]
        if path.endswith(C_SUFFIXES):
            result = strip_c(src)
        elif path.endswith(HASH_SUFFIXES) or name in HASH_NAMES:
            result = strip_py(src)
        else:
            skipped.append((path, "unrecognised"))
            continue
        if result != src:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(result)
    for path, why in skipped:
        print(f"skipped ({why}): {path}", file=sys.stderr)

if __name__ == "__main__":
    main()
