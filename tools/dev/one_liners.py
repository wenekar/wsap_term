#!/usr/bin/env python3
"""List first-party C functions whose body is one single-line statement."""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import threading
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

try:
    import clang.cindex as ci
    from clang.cindex import CursorKind as K
except ImportError:
    print("one_liners: install the libclang Python bindings", file=sys.stderr)
    sys.exit(2)

EPILOG = """categories: unused (no reference), test-only (only tests use it), single-use
(one call), forwarder (passes its parameters unchanged to one call), callback (its
address is taken), helper (the rest). The scan sees only code that the build compiles.
hidden=N counts uses of the name that the scan did not see, such as other platforms,
inactive #if branches, and benchmarks. Check them before you act on a row."""

CATEGORIES = ("unused", "test-only", "single-use", "forwarder", "callback", "helper")
SKIP_ARGS = {"-c", "-MD", "-MMD"}
SKIP_WITH_VALUE = {"-o", "-MF", "-MQ", "-MT"}
SOURCE_SUFFIXES = (".c", ".h", ".m", ".mm", ".inc")


class Scanner:
    def __init__(self, root: Path, multi_line: bool):
        self.root = root
        self.multi_line = multi_line
        self.flags: dict[str, bool] = {}
        self.generated: dict[str, bool] = {}
        self.lock = threading.Lock()
        self.failed: list[str] = []
        try:
            out = subprocess.run(["clang", "-print-resource-dir"], capture_output=True, text=True)
            self.resource_dir = out.stdout.strip() if out.returncode == 0 else ""
        except OSError:
            self.resource_dir = ""

    def clang_accepts(self, flag: str) -> bool:
        with self.lock:
            if flag in self.flags:
                return self.flags[flag]
        try:
            ok = subprocess.run(["clang", "-Werror=unused-command-line-argument", "-fsyntax-only",
                                 "-x", "c", "-", flag], input="", capture_output=True).returncode == 0
        except OSError:
            ok = True
        with self.lock:
            self.flags[flag] = ok
        return ok

    def rel(self, path: str, base: str) -> str | None:
        p = os.path.realpath(os.path.join(base, path))
        root = str(self.root)
        if not p.startswith(root + os.sep):
            return None
        r = p[len(root) + 1:]
        if "/extern/" in r or r.startswith("build") or self.is_generated(p):
            return None
        return r

    def is_generated(self, path: str) -> bool:
        if path not in self.generated:
            try:
                with open(path, "rb") as fh:
                    head = fh.read(512)
            except OSError:
                head = b""
            self.generated[path] = b"Generated by" in head
        return self.generated[path]

    def args(self, entry: dict) -> list[str]:
        raw = entry.get("arguments") or shlex.split(entry["command"])
        out, skip = [], False
        for a in raw[1:]:
            if skip:
                skip = False
            elif a in SKIP_WITH_VALUE:
                skip = True
            elif a in SKIP_ARGS or a.endswith(entry["file"]):
                continue
            elif a.startswith(("-f", "-m")) and not self.clang_accepts(a):
                continue
            else:
                out.append(a)
        out += ["-working-directory", entry["directory"]]
        if self.resource_dir:
            out += ["-resource-dir", self.resource_dir]
        return out

    def parse(self, entry: dict) -> tuple[list[dict], list[tuple[str, str, int, int, bool]],
                                          list[tuple[str, str, int]]]:
        base = entry["directory"]
        src = os.path.join(base, entry["file"])
        try:
            tu = ci.Index.create().parse(src, args=self.args(entry))
        except ci.TranslationUnitLoadError as ex:
            print(f"one_liners: cannot parse {src}: {ex}", file=sys.stderr)
            return [], [], []
        errors = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
        if errors:
            with self.lock:
                self.failed.append(f"{src}: {errors[0].spelling}")
        defs, refs, decls = [], [], []

        def where(cursor):
            f = cursor.location.file
            return self.rel(f.name, base) if f else None

        def definition(cursor, path):
            body = [x for x in cursor.get_children() if x.kind == K.COMPOUND_STMT]
            if not body:
                return
            stmts = list(body[0].get_children())
            if len(stmts) != 1:
                return
            ext = stmts[0].extent
            if not self.multi_line and ext.start.line != ext.end.line:
                return
            with open(os.path.join(base, ext.start.file.name), "rb") as fh:
                fh.seek(ext.start.offset)
                text = fh.read(ext.end.offset - ext.start.offset).decode(errors="replace")
            defs.append({
                "usr": cursor.get_usr(),
                "name": cursor.spelling,
                "file": path,
                "line": cursor.location.line,
                "static": cursor.storage_class == ci.StorageClass.STATIC,
                "params": [a.spelling for a in cursor.get_arguments()],
                "body": " ".join(text.split()).rstrip(";") + ";",
            })

        def walk(cursor, callee):
            if cursor.kind == K.FUNCTION_DECL:
                path = where(cursor)
                if path and cursor.is_definition():
                    definition(cursor, path)
                elif path:
                    decls.append((cursor.get_usr(), path, cursor.location.line))
            elif cursor.kind == K.DECL_REF_EXPR:
                target = cursor.referenced
                if target is not None and target.kind == K.FUNCTION_DECL:
                    path = where(cursor)
                    if path:
                        loc = cursor.location
                        refs.append((target.get_usr(), path, loc.line, loc.column, callee))
            for i, child in enumerate(cursor.get_children()):
                if cursor.kind == K.CALL_EXPR:
                    walk(child, i == 0)
                elif callee and cursor.kind in (K.UNEXPOSED_EXPR, K.PAREN_EXPR):
                    walk(child, True)
                else:
                    walk(child, False)

        for top in tu.cursor.get_children():
            if where(top):
                walk(top, False)
        return defs, refs, decls


def token_counts(root: Path, scanner: Scanner) -> tuple[Counter, dict[str, Counter]]:
    files = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True,
                           text=True).stdout.split("\0")
    total: Counter = Counter()
    per_file: dict[str, Counter] = {}
    for f in files:
        if f.endswith(SOURCE_SUFFIXES) and scanner.rel(f, str(root)):
            text = (root / f).read_text(errors="replace")
            per_file[f] = Counter(re.findall(r"\b[A-Za-z_]\w*\b", text))
            total.update(per_file[f])
    return total, per_file


def is_forwarder(d: dict) -> bool:
    m = re.fullmatch(r"(?:return\s+)?(?:\(void\)\s*)?\w+\s*\((.*)\);", d["body"])
    if not m:
        return False
    args = [a.strip() for a in m.group(1).split(",")] if m.group(1).strip() else []
    return args == d["params"]


def classify(d: dict) -> str:
    is_test = d["file"].startswith("tests/") or "/tests/" in d["file"]
    if d["calls"] + d["addr"] == 0:
        return "unused"
    if d["addr"]:
        return "callback"
    if not is_test and all(f.startswith("tests/") or "/tests/" in f for f in d["ref_files"]):
        return "test-only"
    if d["calls"] == 1:
        return "single-use"
    if is_forwarder(d):
        return "forwarder"
    return "helper"


def find_root(path: Path) -> tuple[Path, Path]:
    build = path.resolve()
    cdb = build / "compile_commands.json"
    if not cdb.is_file():
        print(f"one_liners: no compile_commands.json in {build}", file=sys.stderr)
        sys.exit(2)
    return build.parent, cdb


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, epilog=EPILOG)
    parser.add_argument("build", nargs="?", default="build", help="Meson build directory")
    parser.add_argument("--multi-line", action="store_true",
                        help="also list one-statement bodies that span lines")
    parser.add_argument("--category", action="append", choices=CATEGORIES,
                        help="list only this category; repeat for more")
    parser.add_argument("--prefix", action="append", default=[],
                        help="list only definitions under this path; repeat for more")
    parser.add_argument("--json", action="store_true", help="print JSON")
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 4)
    args = parser.parse_args()

    root, cdb = find_root(Path(args.build))
    scanner = Scanner(root, args.multi_line)
    entries, seen = [], set()
    for e in json.loads(cdb.read_text()):
        src = os.path.realpath(os.path.join(e["directory"], e["file"]))
        if src.endswith(".c") and src not in seen and scanner.rel(src, "/"):
            seen.add(src)
            entries.append(e)

    defs: dict[str, dict] = {}
    refs: dict[str, dict[tuple[str, int, int], bool]] = {}
    decls: dict[str, set[tuple[str, int]]] = {}
    with ThreadPoolExecutor(args.jobs) as pool:
        for found, used, declared in pool.map(scanner.parse, entries):
            for usr, path, line in declared:
                decls.setdefault(usr, set()).add((path, line))
            for d in found:
                defs.setdefault(d["usr"], d)
            for usr, path, line, column, callee in used:
                refs.setdefault(usr, {})[(path, line, column)] = callee

    if scanner.failed:
        for line in scanner.failed:
            print(f"one_liners: parse error in {line}", file=sys.stderr)
        print(f"one_liners: {len(scanner.failed)} sources had parse errors; counts can be wrong",
              file=sys.stderr)

    total, per_file = token_counts(root, scanner)
    rows = []
    for usr, d in defs.items():
        r = refs.get(usr, {})
        d["calls"] = sum(r.values())
        d["addr"] = len(r) - d["calls"]
        local = d["static"] and not d["file"].endswith(".h")
        found = per_file.get(d["file"], Counter()) if local else total
        known = decls.get(usr, set()) | {(d["file"], d["line"])}
        if local:
            known = {k for k in known if k[0] == d["file"]}
        d["hidden"] = max(0, found[d["name"]] - len(known) - len(r))
        d["ref_files"] = sorted({path for path, _, _ in r})
        d["category"] = classify(d)
        if args.category and d["category"] not in args.category:
            continue
        if args.prefix and not d["file"].startswith(tuple(args.prefix)):
            continue
        rows.append(d)
    rows.sort(key=lambda d: (CATEGORIES.index(d["category"]), d["file"], d["line"]))

    if args.json:
        for d in rows:
            del d["usr"]
        json.dump(rows, sys.stdout, indent=1)
        print()
        return 0
    for d in rows:
        hidden = f" hidden={d['hidden']}" if d["hidden"] else ""
        print(f"{d['category']:<10} {d['file']}:{d['line']} {d['name']} "
              f"calls={d['calls']} addr={d['addr']}{hidden}  {d['body']}")
    counts = {c: sum(d["category"] == c for d in rows) for c in CATEGORIES}
    print(f"{len(rows)} functions from {len(entries)} sources: "
          + ", ".join(f"{c} {n}" for c, n in counts.items() if n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
