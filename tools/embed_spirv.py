#!/usr/bin/env python3
"""Compiles GLSL shaders using glslc and embeds them into a C header.

Usage: embed_spirv.py OUTPUT_HEADER SHADER_DIR
"""

import os
import subprocess
import sys
from pathlib import Path

SHADERS = [
    ("glyph.vert", "glyph_vert_spv"),
    ("glyph.frag", "glyph_frag_spv"),
    ("shape.vert", "shape_vert_spv"),
    ("shape.frag", "shape_frag_spv"),
    ("copy.frag", "copy_frag_spv"),
]


def compile_glsl(glsl_path: Path, spv_path: Path):
    cmd = ["glslc", str(glsl_path), "-o", str(spv_path)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"glslc failed for {glsl_path}:\n{res.stderr}")


def embed_spv(name: str, spv_bytes: bytes) -> str:
    # Ensure 4-byte padding
    padded_len = (len(spv_bytes) + 3) & ~3
    spv_bytes = spv_bytes.ljust(padded_len, b'\0')
    words = [int.from_bytes(spv_bytes[i:i+4], 'little') for i in range(0, len(spv_bytes), 4)]

    lines = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(words), 8):
        chunk = words[i:i+8]
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in chunk) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_size = sizeof({name});\n")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 3:
        sys.exit("Usage: embed_spirv.py OUTPUT_HEADER SHADER_DIR")
    out_path = Path(sys.argv[1])
    shader_dir = Path(sys.argv[2])

    tmp_dir = Path("/tmp/embed_spirv")
    tmp_dir.mkdir(parents=True, exist_ok=True)

    header_lines = [
        "/* Generated by tools/embed_spirv.py - DO NOT EDIT DIRECTLY */",
        "#ifndef VULKAN_SHADERS_SPV_H",
        "#define VULKAN_SHADERS_SPV_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]

    for file_name, var_name in SHADERS:
        src = shader_dir / file_name
        spv = tmp_dir / f"{file_name}.spv"
        compile_glsl(src, spv)
        spv_bytes = spv.read_bytes()
        header_lines.append(embed_spv(var_name, spv_bytes))

    header_lines.append("#endif /* VULKAN_SHADERS_SPV_H */\n")
    out_path.write_text("\n".join(header_lines))
    print(f"Generated {out_path}")


if __name__ == "__main__":
    main()
