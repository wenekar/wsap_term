#!/usr/bin/env python3
"""Compiles GLSL shaders with glslc and embeds the SPIR-V in a C header.

Usage: embed_spirv.py GLSLC OUTPUT_HEADER WORK_DIR SHADER...

Each SHADER named `glyph.frag` gives the array `glyph_frag_spv` and its
size in bytes, `glyph_frag_spv_size`. WORK_DIR holds the .spv files.
"""

import subprocess
import sys
from pathlib import Path


def compile_glsl(glslc: str, source: Path, spv: Path) -> bytes:
    res = subprocess.run([glslc, "-O", str(source), "-o", str(spv)],
                         capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"glslc failed for {source}:\n{res.stderr}")
    return spv.read_bytes()


def embed(name: str, spv: bytes) -> str:
    if len(spv) % 4:
        sys.exit(f"{name}: SPIR-V size {len(spv)} is not a multiple of 4")
    words = [int.from_bytes(spv[i:i + 4], "little") for i in range(0, len(spv), 4)]
    lines = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_size = sizeof({name});\n")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 5:
        sys.exit(__doc__)
    glslc, out_path, work_dir = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    work_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Generated by tools/embed_spirv.py. Do not edit. */",
        "#ifndef VULKAN_SHADERS_SPV_H",
        "#define VULKAN_SHADERS_SPV_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    for arg in sys.argv[4:]:
        source = Path(arg)
        name = source.name.replace(".", "_") + "_spv"
        lines.append(embed(name, compile_glsl(glslc, source, work_dir / (source.name + ".spv"))))
    lines.append("#endif\n")
    out_path.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
