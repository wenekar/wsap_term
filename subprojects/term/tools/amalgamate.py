#!/usr/bin/env python3
"""Usage: amalgamate.py WSAP_VTCORE_DIR OUT_DIR [DEPFILE]"""

import re
import sys
from pathlib import Path

INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
PUBLIC = ("wsap_vtcore_types.h", "wsap_vtcore_input.h", "wsap_vtcore.h")

class Joiner:
    def __init__(self, root: Path):
        self.root = root
        src_dirs = tuple(p for p in (root / "src").rglob("*") if p.is_dir())
        self.search = (root / "src",) + src_dirs + (root / "include" / "wsap_vtcore",)
        self.seen: set[Path] = set()

    def resolve(self, name: str, base: Path) -> Path:
        for d in (base,) + self.search:
            p = (d / name).resolve()
            if p.is_file():
                return p
        raise SystemExit(f"{base}: cannot find {name}")

    def emit(self, path: Path, out: list[str]) -> None:
        if path in self.seen:
            return
        self.seen.add(path)
        for line in path.read_text().splitlines(keepends=True):
            m = INCLUDE.match(line)
            if not m:
                out.append(line)
                continue
            dep = self.resolve(m.group(1), path.parent)
            if dep not in self.seen:
                self.emit(dep, out)

def sources(src: Path) -> list[Path]:
    files = sorted(p for p in src.rglob("*.c") if p.is_file())
    return [f.resolve() for f in files]

def main() -> int:
    if len(sys.argv) not in (3, 4):
        print(__doc__, file=sys.stderr)
        return 2
    root = Path(sys.argv[1]).resolve()
    public = root / "include" / "wsap_vtcore"
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    license_file = root / "LICENSE"
    license_text = license_file.read_text()
    banner = ("/*\n * Generated by tools/amalgamate.py. Do not edit.\n *\n" +
              "".join(f" * {line}\n" if line else " *\n"
                      for line in license_text.splitlines()) + " */\n")

    header = Joiner(root)
    text = [banner]
    header.emit(public / "wsap_vtcore.h", text)
    (out_dir / "wsap_vtcore.h").write_text("".join(text))

    body = Joiner(root)
    text = [banner,
            "#if defined(__clang__)\n"
            '#pragma clang diagnostic ignored "-Wunused-function"\n'
            "#endif\n",
            '#include "wsap_vtcore.h"\n']
    body.seen.update((public / name).resolve() for name in PUBLIC)
    for src in sources(root / "src"):
        body.emit(src, text)
    (out_dir / "wsap_vtcore.c").write_text("".join(text))
    if len(sys.argv) == 4:
        read = sorted(header.seen | body.seen | {license_file.resolve(), Path(__file__).resolve()})
        deps = " ".join(str(p).replace(" ", "\\ ") for p in read)
        Path(sys.argv[3]).write_text(f"{out_dir / 'wsap_vtcore.c'}: {deps}\n")
    return 0

if __name__ == "__main__":
    sys.exit(main())
